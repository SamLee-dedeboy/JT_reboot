#!/usr/bin/env python3
"""Generate drilldown/recreationOutflow.ts from Recreation's tiered outflow workbooks.

The sources are the subteam's own workbooks (26 Oct 2026); pass their folder:

  python -I scripts/build-recreation-outflow.py \
      "research/criteria-stories/Recreation/data-2026-10-26"

Each workbook's overall sheet holds, for the three SCHISM tiered outflow runs
(15 Historic Baseline, 16 +30% outflow, 17 -10% outflow), every activity's -5..+5
score by region for the total run, wet seasons and dry seasons, and beneath that
each run's share of days over the activity's threshold in the same cuts. The
report's "Tiered outflow analysis ranking" section is still empty; these sheets
are the only place the numbers are published.
"""

import json
import sys
from pathlib import Path

import openpyxl

OUT = Path("src/internal/rank-visualization/drilldown/recreationOutflow.ts")

BOOKS = {
    "salinity": ("Tiered Outflows Salinity Analyzed.xlsx", "OVERALL"),
    "temperature": ("Tiered Outflows Temperature Analyzed.xlsx", "Overall"),
}

# Score blocks name activities in capitals; the % blocks in title case.
ACTIVITY = {
    "SP DAY USE & BOATING": "dayUseBoating",
    "DAY USE & BOATING": "dayUseBoating",
    "BIRDING": "birding",
    "WATERFOWL": "waterfowl",
    "ANGLING": "angling",
    "DAY USE": "dayUseCold",
}
REGION = {
    "delta-wide": "delta",
    "suisun": "suisun",
    "central": "centralDelta",
    "central delta": "centralDelta",
    "north": "northDelta",
    "north delta": "northDelta",
    "south": "southDelta",
    "south delta": "southDelta",
}
RUNS = ["hist", "more", "less"]
PERIODS = ["run", "wet", "dry"]
# Each period's score block starts at this column: REGION, then the three runs.
SCORE_COLUMNS = {"run": 3, "wet": 9, "dry": 15}
PCT_BLOCKS = {"RUN 15": "hist", "RUN 16": "more", "RUN 17": "less"}
PCT_REGIONS = ["delta", "suisun", "centralDelta", "northDelta", "southDelta"]


def activity_key(label: str) -> str | None:
    text = " ".join(str(label).upper().split())
    if text.startswith("SP DAY USE"):
        return "dayUseBoating"
    return ACTIVITY.get(text)


def number(value) -> float | None:
    try:
        return round(float(value), 4)
    except (TypeError, ValueError):
        return None


def read(path: Path, sheet: str):
    rows = list(openpyxl.load_workbook(path, data_only=True)[sheet].iter_rows(values_only=True))
    cell = lambda r, c: rows[r][c] if r < len(rows) and c < len(rows[r]) else None
    scores: dict = {}
    days: dict = {}

    # Scores: an activity name in column 2 opens five region rows.
    for r in range(len(rows)):
        key = activity_key(cell(r, 2)) if cell(r, 2) else None
        if not key or str(cell(r, 2)).upper().startswith(("RUN ", "TIERED")):
            continue
        if not isinstance(cell(r, 3), str) or cell(r, 3).lower() != "delta-wide":
            continue
        for offset in range(5):
            for period, col in SCORE_COLUMNS.items():
                region = REGION.get(str(cell(r + offset, col) or "").strip().lower())
                if not region:
                    continue
                for i, run in enumerate(RUNS):
                    value = number(cell(r + offset, col + 1 + i))
                    scores.setdefault(key, {}).setdefault(run, {}).setdefault(region, {})[period] = value

    # Days over the threshold: "RUN 15 % EXCEEDANCES", two header rows, then activities.
    for r in range(len(rows)):
        label = str(cell(r, 2) or "")
        run = next((v for k, v in PCT_BLOCKS.items() if label.upper().startswith(k)), None)
        if not run:
            continue
        for rr in range(r + 3, r + 9):
            key = activity_key(cell(rr, 2)) if cell(rr, 2) else None
            if not key:
                break
            for p, period in enumerate(PERIODS):
                for g, region in enumerate(PCT_REGIONS):
                    value = number(cell(rr, 3 + p * 5 + g))
                    days.setdefault(key, {}).setdefault(run, {}).setdefault(region, {})[period] = value
    return scores, days


def main() -> None:
    folder = Path(sys.argv[1] if len(sys.argv) > 1 else "research/criteria-stories/Recreation/data-2026-10-26")
    out = [
        "// Generated by scripts/build-recreation-outflow.py — do not edit by hand.",
        "//",
        "// Recreation's tiered outflow runs (SCHISM runs 15, 16, 17; Oct 2020 – Jan 2022),",
        "// from the subteam's 26 Oct 2026 workbooks. Each activity's −5…+5 score and its",
        "// share of days over the threshold, by region and by whole run, wet and dry",
        "// seasons, against the Historic Baseline (run 15).",
        "import type { RecActivityKey } from './recreationThresholds'",
        "",
        "export type OutflowRun = 'hist' | 'more' | 'less'",
        "type Table = Partial<",
        "  Record<RecActivityKey, Record<OutflowRun, Record<string, Record<string, number | null>>>>",
        ">",
        "",
    ]
    for metric, (book, sheet) in BOOKS.items():
        scores, days = read(folder / book, sheet)
        name = metric.upper()
        out.append(f"export const REC_OUTFLOW_{name}_SCORES: Table = {json.dumps(scores, indent=2)}")
        out.append("")
        out.append(f"export const REC_OUTFLOW_{name}_DAYS: Table = {json.dumps(days, indent=2)}")
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
