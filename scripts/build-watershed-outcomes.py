#!/usr/bin/env python3
"""Generate src/internal/watershed/outcomes.ts from the upland restoration workbook.

The source is Maggie Gallagher's "NGW Upland Restoration Scenario Outcomes"
workbook (v4, October 2026), outside the repo; pass its path:

  python3 -I scripts/build-watershed-outcomes.py \
      "tmp/watershed/NGW Upland Restoration Scenario Outcomes_v4.xlsx"

Sheet1 holds three blocks read here:
  - the scenario matrix (E5:I16): share of each landscape treated, by
    restoration level and the landscape a scenario prioritizes;
  - restorable acres (K5:L10);
  - TABLE 2 (B52 onward): low and high totals for each scenario.

The workbook's vis_export sheet differs from TABLE 2 and is not used.
"""

import json
import sys

import openpyxl

OUT = "src/internal/watershed/outcomes.ts"

LEVELS = {"minimal restoration": "min", "medium restoration": "med", "maximum restoration": "max"}
PRIORITY_COLUMNS = {"G": "forest", "H": "meadow", "I": "floodplain"}
LANDSCAPES = {"forests": "forests", "meadows": "meadows", "floodplains": "floodplains"}
SCENARIO = {"min": "min", "med": "med", "max": "max"}
PRIORITY = {"forests": "forest", "meadows": "meadow", "floodplains": "floodplain"}

# TABLE 2 header text → metric key used by the page.
METRICS = {
    "change in et": "et",
    "change in runoff": "runoff",
    "change in gw recharge": "gwRecharge",
    "change in forest cover": "forestCover",
    "change in meadow wetland cover": "meadowWetland",
    "change in riparian cover": "riparian",
    "change in marsh cover": "marsh",
    "change in carbon storage (annual)": "carbonAnnual",
    "change in carbon storage (veg at maturity)": "carbonVegetation",
}

RESTORABLE = {
    "forests - total": "forests",
    "meadows": "meadows",
    "floodplains - baseline": "floodplainOpportunity",
    "floodplains - max": "floodplainNeed",
}


def text(value):
    return str(value).strip().lower() if value is not None else ""


def main(path):
    ws = openpyxl.load_workbook(path, data_only=True)["Sheet1"]

    # Scenario matrix: a level label in E starts each block of three landscape rows.
    treatment = {}
    level = None
    for row in range(5, 17):
        label = text(ws[f"E{row}"].value)
        if label in LEVELS:
            level = LEVELS[label]
        elif label:
            level = None
        landscape = LANDSCAPES.get(text(ws[f"F{row}"].value))
        if not level or not landscape:
            continue
        for column, priority in PRIORITY_COLUMNS.items():
            share = ws[f"{column}{row}"].value
            treatment.setdefault(level, {}).setdefault(priority, {})[landscape] = round(share, 4)

    restorable = {}
    for row in range(5, 11):
        key = RESTORABLE.get(text(ws[f"K{row}"].value))
        if key:
            restorable[key] = ws[f"L{row}"].value

    # TABLE 2: find its header row, then read low/high pairs per scenario.
    header_row = next(
        r for r in range(40, ws.max_row + 1) if text(ws[f"D{r}"].value) == "change in et"
    )
    columns = {}
    for cell in ws[header_row]:
        key = METRICS.get(text(cell.value))
        if key:
            columns[key] = (cell.column_letter, ws[f"{cell.column_letter}{header_row + 1}"].value)

    outcomes = []
    scenario = None
    for row in range(header_row + 2, header_row + 2 + 18):
        name = text(ws[f"B{row}"].value)
        if name:
            lvl, landscape = name.split("-")
            scenario = (SCENARIO[lvl], PRIORITY[landscape])
        bound = text(ws[f"C{row}"].value)
        if not scenario or bound not in ("low", "high"):
            continue
        for key, (column, _unit) in columns.items():
            value = ws[f"{column}{row}"].value
            match = next(
                (o for o in outcomes if (o["level"], o["priority"], o["metric"]) == (*scenario, key)),
                None,
            )
            if match is None:
                match = {"level": scenario[0], "priority": scenario[1], "metric": key}
                outcomes.append(match)
            match[bound] = round(value, 4)

    units = {key: unit for key, (_column, unit) in columns.items()}
    missing = [k for k in METRICS.values() if k not in units]
    if missing or len(outcomes) != 9 * len(METRICS):
        sys.exit(f"Unexpected workbook layout: missing {missing}, {len(outcomes)} outcomes")

    body = "\n".join(
        [
            "// Generated by scripts/build-watershed-outcomes.py from the NGW Upland Restoration",
            "// Scenario Outcomes workbook (v4). Do not edit by hand; rerun the script instead.",
            "import type { WatershedOutcome, WatershedOutcomeMetric } from './types'",
            "",
            "/** Restorable acres per landscape in the Bay-Delta watershed upstream of the Delta. */",
            f"export const restorableAcres = {json.dumps(restorable, indent=2)} as const",
            "",
            "/** Share of each landscape treated, by restoration level and prioritized landscape. */",
            f"export const treatmentShares = {json.dumps(treatment, indent=2)} as const",
            "",
            "/** Units of each TABLE 2 metric, as the workbook states them. */",
            "export const outcomeUnits: Record<WatershedOutcomeMetric, string> = "
            f"{json.dumps(units, indent=2)}",
            "",
            "/** TABLE 2: low and high totals per scenario and metric. */",
            f"export const outcomes: WatershedOutcome[] = {json.dumps(outcomes, indent=2)}",
            "",
        ]
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(body)
    print(f"Wrote {OUT}: {len(outcomes)} outcomes")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
