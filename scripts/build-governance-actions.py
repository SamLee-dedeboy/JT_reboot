"""Build src/features/governance/data/actions.ts from the governance team's scores.

Input: scenario_scores_by_action.csv from the transgov repository (deltagov v0.6.0),
the team's coding of every Delta Adapts Adaptation Plan (2025) action against the
adaptation scenarios, and da_strategies_orgs.csv beside it, the lead and partner
organizations the plan names for each strategy. Both are gitignored and stay local,
for example under tmp/governance/data/.

    python scripts/build-governance-actions.py tmp/governance/data/scenario_scores_by_action.csv
"""

import csv
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/features/governance/data/actions.ts"

# CSV column -> ScenarioKey in src/content/names.ts
COLUMNS = {
    "Tunnel": "tunnel",
    "Calling on Reserves": "cor",
    "Bolster & Fortify": "bf",
    "30% Increased Tiered Outflow": "more",
    "Eco Machine": "em",
    "New Green Watershed": "ngw",
}

# Lead organization (da_strategies_orgs.csv entity) -> LeadKey in data/types.ts. Water
# suppliers, utilities and reservoir operators are groups, not agencies, and share a lane.
LEADS = {
    "California Natural Resources Agency": "cnra",
    "Delta Stewardship Council": "dsc",
    "California Department of Water Resources": "dwr",
    "State Water Resources Control Board": "swrcb",
    "Sacramento-San Joaquin Delta Conservancy": "conservancy",
    "California Department of Food and Agriculture": "cdfa",
    "Water Suppliers": "suppliers",
    "Water Utilities": "suppliers",
    "Reservoir Operators": "suppliers",
    "Delta Agencies": "deltaAgencies",
}


def strategy_orgs(path: Path) -> tuple[dict[str, list[str]], dict[str, int]]:
    """Each strategy's lead keys, and how many partners it names."""
    leads: dict[str, list[str]] = {}
    partners: dict[str, set[str]] = {}
    with open(path, encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            strategy = row["strategy_id"].strip()
            if row["strategy_role_type"].strip() == "lead":
                key = LEADS[row["entity"].strip()]
                if key not in leads.setdefault(strategy, []):
                    leads[strategy].append(key)
            else:
                partners.setdefault(strategy, set()).add(row["jtid"].strip())
    return leads, {strategy: len(ids) for strategy, ids in partners.items()}


def first_sentence(text: str) -> str:
    text = " ".join(text.split())
    match = re.match(r"(.+?\.)(\s|$)", text)
    return match.group(1) if match else text


def main(src: str) -> None:
    with open(src, encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    leads, partners = strategy_orgs(Path(src).with_name("da_strategies_orgs.csv"))

    strategies: dict[str, str] = {}
    actions = []
    strategy = ""
    for row in rows:
        strategy = row["strategy_id"].strip() or strategy
        if row["strategy_desc"].strip() and strategy not in strategies:
            strategies[strategy] = first_sentence(row["strategy_desc"])
        text = re.sub(r"^[A-Z]+-\d+-\d+:\s*", "", row["action"].strip())
        scores = {key: round(float(row[column]), 2) for column, key in COLUMNS.items()}
        actions.append(
            {
                "id": row["action_id"].strip(),
                "strategy": strategy,
                "area": strategy.split("-")[0],
                "text": " ".join(text.split()),
                "scores": scores,
                "leads": leads[strategy],
                "partners": partners.get(strategy, 0),
            }
        )

    body = [
        "// Generated by scripts/build-governance-actions.py from the governance team's",
        "// scenario_scores_by_action.csv (transgov, deltagov v0.6.0). Don't edit by hand.",
        "import type { GovernanceAction } from './types'",
        "",
        "/** Each strategy's opening sentence, by strategy id (FL-1, ECO-3, ...). */",
        "export const STRATEGIES: Record<string, string> = "
        + json.dumps(strategies, ensure_ascii=False, indent=2),
        "",
        "/** All 129 Adaptation Plan actions with their alignment score per scenario. */",
        "export const ACTIONS: GovernanceAction[] = "
        + json.dumps(actions, ensure_ascii=False, indent=2),
        "",
    ]
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"{len(actions)} actions, {len(strategies)} strategies -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
